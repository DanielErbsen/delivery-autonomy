"""Rasterise the planner's sidewalk graph into a Nav2 occupancy map."""
import argparse
import os
import struct
import zlib

import numpy as np

from autonomy.global_planner import GlobalPlanningServer

# Pixel values that map_server reads as free and occupied in trinary mode
FREE = 254
OCCUPIED = 0

class GraphLoader:
    """Stands in for the planner node so that its graph loads without ROS."""
    def get_logger(self):
        return self

    def info(self, message):
        print(message)

def edge_polylines(graph, origin):
    """Return every edge as an (N, 2) array of points in the map frame."""
    polylines = []
    for u, v, data in graph.edges(data=True):
        if 'geometry' in data:
            xs, ys = data['geometry'].xy
        else:
            xs = (graph.nodes[u]['x'], graph.nodes[v]['x'])
            ys = (graph.nodes[u]['y'], graph.nodes[v]['y'])
        polylines.append(np.column_stack((xs, ys)) - np.asarray(origin))
    return polylines

def rasterize(polylines, half_width, resolution, margin):
    """Mark the cells within half_width of any polyline as free.

    Returns the mask, with row 0 in the south, and the map-frame position of
    its south-west corner.
    """
    points = np.vstack(polylines)
    corner = points.min(axis=0) - half_width - margin
    extent = points.max(axis=0) + half_width + margin - corner
    width, height = np.ceil(extent / resolution).astype(int)
    free = np.zeros((height, width), dtype=bool)

    for polyline in polylines:
        for a, b in zip(polyline[:-1], polyline[1:]):
            # Only the cells around this segment can be within reach of it
            lo = np.floor((np.minimum(a, b) - half_width - corner) / resolution).astype(int)
            hi = np.ceil((np.maximum(a, b) + half_width - corner) / resolution).astype(int) + 1
            lo = np.maximum(lo, 0)
            hi = np.minimum(hi, (width, height))
            xs = corner[0] + (np.arange(lo[0], hi[0]) + 0.5) * resolution
            ys = corner[1] + (np.arange(lo[1], hi[1]) + 0.5) * resolution
            px, py = np.meshgrid(xs, ys)

            # Distance from each cell centre to the closest point of the segment
            d = b - a
            length2 = d @ d
            t = 0.0
            if length2 > 0.0:
                t = np.clip(((px - a[0]) * d[0] + (py - a[1]) * d[1]) / length2, 0.0, 1.0)
            dist2 = (px - a[0] - t * d[0])**2 + (py - a[1] - t * d[1])**2
            free[lo[1]:hi[1], lo[0]:hi[0]] |= dist2 <= half_width**2

    return free, corner

def write_png(path, pixels):
    """Write an 8-bit greyscale image. PNG keeps a two-colour map small."""
    height, width = pixels.shape

    def chunk(tag, data):
        return (struct.pack('>I', len(data)) + tag + data
                + struct.pack('>I', zlib.crc32(tag + data)))

    # Each row starts with a filter byte; 0 means the row is stored as it is
    rows = b''.join(b'\x00' + row.tobytes() for row in pixels)
    with open(path, 'wb') as f:
        f.write(b'\x89PNG\r\n\x1a\n')
        f.write(chunk(b'IHDR', struct.pack('>IIBBBBB', width, height, 8, 0, 0, 0, 0)))
        f.write(chunk(b'IDAT', zlib.compress(rows, 9)))
        f.write(chunk(b'IEND', b''))

def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--half-width', type=float, default=1.5,
                        help='free distance to each side of an edge, in meters')
    parser.add_argument('--resolution', type=float, default=0.1,
                        help='cell size, in meters')
    parser.add_argument('--margin', type=float, default=5.0,
                        help='occupied border around the graph, in meters')
    parser.add_argument('--output-dir', default=os.path.join('src', 'autonomy', 'maps'))
    parser.add_argument('--name', default='boundary')
    args = parser.parse_args()

    graph, origin = GlobalPlanningServer._initialize_graph(GraphLoader())
    polylines = edge_polylines(graph, origin)
    free, corner = rasterize(polylines, args.half_width, args.resolution, args.margin)

    # Image rows run north to south, the opposite of the mask
    pixels = np.where(free[::-1], FREE, OCCUPIED).astype(np.uint8)

    os.makedirs(args.output_dir, exist_ok=True)
    write_png(os.path.join(args.output_dir, args.name + '.png'), pixels)
    with open(os.path.join(args.output_dir, args.name + '.yaml'), 'w') as f:
        f.write(
            '# Generated by `ros2 run autonomy boundary_map`. Do not edit.\n'
            f'# {len(polylines)} graph edges, free within {args.half_width} m of each. Frame: map.\n'
            f'image: {args.name}.png\n'
            'mode: trinary\n'
            f'resolution: {args.resolution}\n'
            f'origin: [{corner[0]:.3f}, {corner[1]:.3f}, 0.0]\n'
            'negate: 0\n'
            'occupied_thresh: 0.65\n'
            'free_thresh: 0.25\n')

    print(f'{args.name}.png: {pixels.shape[1]} x {pixels.shape[0]} cells at {args.resolution} m, '
          f'{100.0 * free.mean():.1f}% free, origin ({corner[0]:.1f}, {corner[1]:.1f})')

if __name__ == '__main__':
    main()
